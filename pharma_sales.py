"""## STEP 6: — Use Of Map & Reduce

1 : Which medicines generate the highest total sales?
"""

medicine_sales = (
    etl_df.rdd.map(lambda row: (
        row["medicine"],
        float(row["total_sales"])
    ))
    .reduceByKey(lambda a, b: a + b)
)

top_medicines_sales = (
    medicine_sales
    .sortBy(lambda x: x[1], ascending=False)
    .take(10)
)

